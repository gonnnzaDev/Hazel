#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Recop — everyday commands
#
#     ./scripts/recop.sh <command>
#
# The Makefile equivalent for anyone without make (Windows, Android,
# or simply anyone who doesn't have it installed). Each command does the same
# as its Makefile target, so both work.
#
#     ./scripts/recop.sh up        # start PostgreSQL and Kafka
#     ./scripts/recop.sh api       # start the node
#     ./scripts/recop.sh check     # lint + format + types + tests
#     ./scripts/recop.sh help      # show all commands
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

COMPOSE="docker compose -f docker-compose.dev.yml"
STACK="docker compose"

need_docker() {
    if ! command -v docker >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then
        printf 'docker is not available.\n' >&2
        # $USER and $PREFIX stay literal: they are part of the command the user
        # has to copy-paste, not something we want to expand here.
        # shellcheck disable=SC2016
        printf '  Linux:     sudo usermod -aG docker $USER  (and log back in)\n' >&2
        printf '  macOS:     open Docker Desktop\n' >&2
        printf '  Windows:   open Docker Desktop\n' >&2
        printf '  Android:   install the docker package in Termux\n' >&2
        exit 1
    fi
}

wait_for_postgres() {
    local user="recop"
    if [ -f .env ]; then
        user="$(awk -F= '/^POSTGRES_USER=/ {print $2}' .env | head -1)"
        [ -n "$user" ] || user="recop"
    fi
    printf '    waiting for PostgreSQL...'
    for _ in $(seq 1 60); do
        if $COMPOSE exec -T postgres pg_isready -U "$user" >/dev/null 2>&1; then
            printf ' ready\n'
            return 0
        fi
        sleep 1
    done
    printf ' did not respond\n' >&2
    return 1
}

cmd_up() {
    need_docker
    $COMPOSE up -d
    wait_for_postgres
}

cmd_down()     { need_docker; $COMPOSE down; }
cmd_reset()    { need_docker; $COMPOSE down -v; }
cmd_logs()     { need_docker; $COMPOSE logs -f; }
cmd_stack_up() { need_docker; $STACK up -d --build; }
cmd_stack_down(){ need_docker; $STACK down; }
cmd_stack_logs(){ need_docker; $STACK logs -f api; }

cmd_api()        { uv run python -m core --reload; }
cmd_migrate()    { uv run alembic upgrade head; }
cmd_downgrade()  { uv run alembic downgrade "${1:--1}"; }

cmd_revision() {
    if [ -z "${1:-}" ]; then
        printf 'usage: ./scripts/recop.sh revision "message"\n' >&2
        exit 1
    fi
    uv run alembic revision --autogenerate -m "$1"
}

cmd_lint()      { uv run ruff check .; }
cmd_format()    { uv run ruff format .; }
cmd_typecheck() { uv run mypy src; }
cmd_test()      { uv run pytest "$@"; }

cmd_test_integration() {
    if [ -z "${RECOP_TEST_DATABASE_URL:-}" ]; then
        printf 'Missing RECOP_TEST_DATABASE_URL. E.g.:\n' >&2
        printf '  ./scripts/recop.sh test-integration RECOP_TEST_DATABASE_URL=postgresql+asyncpg://recop:recop@localhost:5432/recop_test\n' >&2
        exit 1
    fi
    uv run pytest "$@"
}

cmd_check() {
    cmd_lint && cmd_format && cmd_typecheck && cmd_test
}

cmd_health() {
    port="$(awk -F= '/^RECOP_PORT=/ {print $2}' .env 2>/dev/null | head -1)"
    port="${port:-7272}"
    printf 'node health on localhost:%s\n\n' "$port"
    curl -sS "http://localhost:${port}/health" && printf '\n\n' || printf 'the node is not responding on port %s\n' "$port"
    curl -sS "http://localhost:${port}/health/ready" && printf '\n' || printf 'the node is not responding on port %s\n' "$port"
}

cmd_help() {
    cat <<'EOF'
Recop — commands

  Development
    up                Start PostgreSQL and Kafka
    down              Stop them (keeping the data)
    reset             Stop them and delete the volumes (destructive)
    logs              Follow the service logs
    api               Start the node with reload
    migrate           Apply the migrations
    downgrade [rev]   Revert migrations (one by default)
    revision "msg"    Create an autogenerated migration

    lint              Lint
    format            Format
    typecheck         Type check
    test [args]       Run the tests
    test-integration  Tests against a real database
    check             lint + format + typecheck + test

    health            Ask the node how it is doing

  Full stack (everything in containers)
    stack-up          Start node + PostgreSQL + Kafka
    stack-down        Stop them
    stack-logs        Node logs

  Other
    help              This help

Examples
    ./scripts/recop.sh up
    ./scripts/recop.sh test-integration RECOP_TEST_DATABASE_URL=postgresql+asyncpg://recop:recop@localhost:5432/recop_test
EOF
}

main() {
    local cmd="${1:-help}"
    shift || true

    case "$cmd" in
        up)               cmd_up ;;
        down)             cmd_down ;;
        reset)            cmd_reset ;;
        logs)             cmd_logs ;;
        stack-up)         cmd_stack_up ;;
        stack-down)       cmd_stack_down ;;
        stack-logs)       cmd_stack_logs ;;
        api)              cmd_api ;;
        migrate)          cmd_migrate ;;
        downgrade)        cmd_downgrade "$@" ;;
        revision)         cmd_revision "$@" ;;
        lint)             cmd_lint ;;
        format)           cmd_format ;;
        typecheck)        cmd_typecheck ;;
        test)             cmd_test "$@" ;;
        test-integration) cmd_test_integration "$@" ;;
        check)            cmd_check ;;
        health)           cmd_health ;;
        help|-h|--help)   cmd_help ;;
        *)
            printf 'unknown command: %s\n\n' "$cmd" >&2
            cmd_help >&2
            exit 1
            ;;
    esac
}

main "$@"